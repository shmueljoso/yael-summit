/** A server string in a language, with {placeholders} filled in. */
export function tr(lang, key, vars = {}) {
  const s = D[okLang(lang)]?.[key] ?? D.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

/** "a, b and c" in a language. */
export function listIn(lang, items) {
  const and = tr(lang, "and");
  if (items.length <= 1) return items.join("");
  const sep = okLang(lang) === "he" ? ` ${and}` : ` ${and} `;
  return `${items.slice(0, -1).join(", ")}${sep}${items[items.length - 1]}`;
}

